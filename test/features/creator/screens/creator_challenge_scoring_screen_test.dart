import 'dart:convert';

import 'package:flutter/material.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:http/http.dart' as http;
import 'package:http/testing.dart';
import 'package:shared_preferences/shared_preferences.dart';

import 'package:aura_app/core/services/api_client.dart';
import 'package:aura_app/features/creator/screens/creator_challenge_scoring_screen.dart';
import 'package:aura_app/features/creator/screens/creator_challenge_status_screen.dart';

// The creator builds scoring criteria before submitting (backend ADR 137): generate with
// AI, edit names/points, save — and is never left able to submit without criteria
// unknowingly. Before this, the draft form's "scoring criteria" were display text only and
// published challenges couldn't be played ("Challenge not ready").
void main() {
  late List<http.Request> sent;
  late Map<String, dynamic> rubricView;

  Map<String, dynamic> generated() => {
        'hasRubric': true,
        'editable': true,
        'source': 'ai',
        'fixedCategories': [
          {'key': 'reference_similarity', 'name': 'Reference Similarity', 'maxPoints': 5},
          {'key': 'framing_visibility', 'name': 'Framing', 'maxPoints': 5},
        ],
        'categories': [
          for (var i = 0; i < 6; i++)
            {'key': 'k$i', 'name': 'Skill $i', 'description': 'Look for $i', 'maxPoints': i == 0 ? 15 : 14},
        ],
        'bonusRules': [],
        'rules': {'categoryPointsTotal': 85, 'minCategories': 6, 'maxCategories': 8, 'minPoints': 5, 'maxPoints': 30},
      };

  setUp(() {
    sent = [];
    FlutterSecureStorage.setMockInitialValues({
      'api_access_token': 'token',
      'api_refresh_token': 'refresh',
      'api_user_id': 'creator-1',
    });
    SharedPreferences.setMockInitialValues({});
    rubricView = {'hasRubric': false, 'editable': true, 'categories': [], 'fixedCategories': [], 'bonusRules': []};

    ApiClient.httpClient = MockClient((req) async {
      sent.add(req);
      final path = req.url.path;
      if (path.endsWith('/rubric/generate')) {
        rubricView = generated();
      } else if (path.endsWith('/rubric') && req.method == 'PUT') {
        final body = jsonDecode(req.body) as Map<String, dynamic>;
        rubricView = {...generated(), 'source': 'manual', 'categories': body['categories']};
      } else if (path.endsWith('/creator/challenges/ch-1')) {
        return http.Response(
          jsonEncode({
            'status': 'success',
            'data': {
              'challenge': {
                '_id': 'ch-1',
                'title': 'Box Jump',
                'description': 'Jump on the box.',
                'difficulty': 'Easy',
                'submissionStatus': 'DRAFT',
              },
            },
          }),
          200,
        );
      } else if (!path.endsWith('/rubric')) {
        return http.Response(jsonEncode({'status': 'success', 'data': {}}), 200);
      }
      return http.Response(jsonEncode({'status': 'success', 'data': rubricView}), 200);
    });
  });
  tearDown(() => ApiClient.httpClient = http.Client());

  Future<void> settle(WidgetTester tester) async {
    await tester.runAsync(() => Future<void>.delayed(const Duration(milliseconds: 200)));
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 100));
  }

  Future<void> open(WidgetTester tester, Widget screen) async {
    tester.view.physicalSize = const Size(1080, 4000);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.reset);
    await tester.pumpWidget(MaterialApp(home: screen));
    await settle(tester);
  }

  testWidgets('generate, edit points and save sends the edited criteria', (tester) async {
    await open(tester, const CreatorChallengeScoringScreen(challengeId: 'ch-1'));
    expect(find.text('Generate scoring criteria'), findsOneWidget);

    await tester.tap(find.text('Generate scoring criteria'));
    await settle(tester);
    expect(find.text('Skill 0'), findsOneWidget);
    expect(find.text('Generated by AI'), findsOneWidget);

    await tester.tap(find.text('Edit'));
    await tester.pump();
    expect(find.byKey(const Key('points-total')), findsOneWidget);
    expect(find.text('100 / 100'), findsOneWidget);

    // Unbalanced points block the save with a clear message.
    await tester.tap(find.byKey(const Key('points-plus-0')));
    await tester.pump();
    expect(find.text('101 / 100'), findsOneWidget);
    await tester.tap(find.text('Save criteria'));
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 500));
    expect(find.textContaining('Remove 1 point'), findsOneWidget);
    expect(sent.where((r) => r.method == 'PUT'), isEmpty);

    // Rebalance, rename, save.
    await tester.tap(find.byKey(const Key('points-minus-1')));
    await tester.enterText(find.byKey(const Key('category-name-0')), 'Clean landing');
    await tester.pump();
    await tester.tap(find.text('Save criteria'));
    await settle(tester);

    final put = sent.lastWhere((r) => r.method == 'PUT');
    final categories = (jsonDecode(put.body)['categories'] as List).cast<Map<String, dynamic>>();
    expect(categories.first, {'key': 'k0', 'name': 'Clean landing', 'description': 'Look for 0', 'maxPoints': 16});
    expect(categories[1]['maxPoints'], 13);
    expect(find.text('Edited by you'), findsOneWidget);
    expect(find.text('Clean landing'), findsOneWidget);
  });

  testWidgets('regenerate sends the notes', (tester) async {
    rubricView = generated();
    await open(tester, const CreatorChallengeScoringScreen(challengeId: 'ch-1'));

    await tester.tap(find.text('Ask AI for changes'));
    await tester.pumpAndSettle();
    await tester.enterText(find.byKey(const Key('regenerate-notes')), 'Focus on the landing');
    await tester.tap(find.text('Regenerate'));
    await tester.pumpAndSettle();
    await settle(tester);

    final gen = sent.lastWhere((r) => r.url.path.endsWith('/rubric/generate'));
    expect(jsonDecode(gen.body), {'notes': 'Focus on the landing'});
  });

  testWidgets('criteria are read-only once the challenge is in review', (tester) async {
    rubricView = {...generated(), 'editable': false};
    await open(tester, const CreatorChallengeScoringScreen(challengeId: 'ch-1'));

    expect(find.text('Skill 0'), findsOneWidget);
    expect(find.text('Edit'), findsNothing);
    expect(find.text('Ask AI for changes'), findsNothing);
  });

  testWidgets('submitting a draft without criteria asks to set them up first', (tester) async {
    await open(tester, const CreatorChallengeStatusScreen(challengeId: 'ch-1'));
    expect(find.textContaining('required before you submit'), findsOneWidget);

    await tester.tap(find.text('Submit for Review'));
    await tester.pumpAndSettle();
    expect(find.text('Scoring criteria needed'), findsOneWidget);

    await tester.tap(find.text('Set up now'));
    await tester.pumpAndSettle();
    expect(find.byType(CreatorChallengeScoringScreen), findsOneWidget);
    expect(sent.where((r) => r.url.path.endsWith('/submit')), isEmpty);
  });

  testWidgets('a draft with criteria submits without the prompt', (tester) async {
    rubricView = generated();
    await open(tester, const CreatorChallengeStatusScreen(challengeId: 'ch-1'));
    expect(find.textContaining('6 categories'), findsOneWidget);

    await tester.tap(find.text('Submit for Review'));
    await tester.pumpAndSettle();
    expect(find.text('Scoring criteria needed'), findsNothing);
  });

  testWidgets('criteria that do not add up to 100 are flagged with a clear message', (tester) async {
    rubricView = {...generated(), 'totalPoints': 105};
    await open(tester, const CreatorChallengeScoringScreen(challengeId: 'ch-1'));
    expect(find.text('Out of 105'), findsOneWidget);
    expect(find.textContaining('add up to 105 points instead of 100'), findsOneWidget);
  });

  testWidgets('generated criteria show "Out of 100" and no warning', (tester) async {
    rubricView = {...generated(), 'totalPoints': 100};
    await open(tester, const CreatorChallengeScoringScreen(challengeId: 'ch-1'));
    expect(find.text('Out of 100'), findsOneWidget);
    expect(find.byKey(const Key('rubric-total-warning')), findsNothing);
  });
}
